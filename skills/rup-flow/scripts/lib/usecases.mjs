import fs from 'node:fs';
import path from 'node:path';

export const INDEX_START = '<!-- rup-flow:use-cases:start -->';
export const INDEX_END = '<!-- rup-flow:use-cases:end -->';
const DISCIPLINES = ['requirements', 'analysis', 'design', 'implementation'];

function parseFront(text) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text);
  const data = {};
  if (!match) return data;
  for (const line of match[1].split(/\r?\n/)) {
    const pair = /^([\w-]+):\s*(.*)$/.exec(line);
    if (pair) data[pair[1]] = pair[2].trim().replace(/^"(.*)"$/, '$1');
  }
  return data;
}

function list(value) {
  return String(value ?? '').split(',').map((s) => s.trim()).filter(Boolean);
}

/** Reads the use-case cards of the requirements discipline. */
export function readUseCases(base, config) {
  const reqDir = path.join(base, config.paths.requirements, config.useCaseDir);
  if (!fs.existsSync(reqDir)) return [];
  const cases = [];
  for (const entry of fs.readdirSync(reqDir, { withFileTypes: true }).filter((e) => e.isDirectory()).sort((a, b) => a.name.localeCompare(b.name))) {
    const card = path.join(reqDir, entry.name, 'README.md');
    if (!fs.existsSync(card)) continue;
    const front = parseFront(fs.readFileSync(card, 'utf8'));
    const present = {};
    for (const discipline of DISCIPLINES) present[discipline] = fs.existsSync(path.join(base, config.paths[discipline], config.useCaseDir, entry.name, 'README.md'));
    cases.push({
      name: entry.name,
      id: front.id ?? '',
      title: front.title || entry.name,
      actors: list(front.actor || 'Actor'),
      package: front.package || 'General',
      status: front.status || 'draft',
      requirement: front.requirement ?? '',
      includes: list(front.includes),
      extendsCases: list(front.extends),
      present,
    });
  }
  return cases.sort((a, b) => a.id.localeCompare(b.id, undefined, { numeric: true }) || a.name.localeCompare(b.name));
}

const slug = (text) => text.replace(/[^A-Za-z0-9]+/g, '_').replace(/^_+|_+$/g, '') || 'x';
const q = (text) => text.replace(/"/g, "'");

export function actorsOf(cases) {
  return [...new Set(cases.flatMap((c) => c.actors))].sort((a, b) => a.localeCompare(b));
}

function subset(cases, actor) {
  if (!actor) return cases;
  const own = cases.filter((c) => c.actors.includes(actor));
  const names = new Set(own.map((c) => c.name));
  for (let pass = 0; pass < 2; pass++) {
    for (const c of cases) {
      if (names.has(c.name)) continue;
      const linked = own.some((o) => o.includes.includes(c.name) || o.extendsCases.includes(c.name)) || cases.some((x) => names.has(x.name) && (x.includes.includes(c.name) || x.extendsCases.includes(c.name)));
      if (linked) names.add(c.name);
    }
  }
  return cases.filter((c) => names.has(c.name));
}

function groupByPackage(cases) {
  const groups = new Map();
  for (const c of cases) groups.set(c.package, [...(groups.get(c.package) ?? []), c]);
  return groups;
}

function primary(c, used) {
  return !used.some((o) => o !== c && o.actors.some((a) => c.actors.includes(a)) && (o.includes.includes(c.name) || o.extendsCases.includes(c.name)));
}

/** PlantUML use-case diagram: actors outside a system boundary, use cases in packages. */
export function overviewPlantuml(cases, project, actor) {
  const used = subset(cases, actor);
  const names = new Set(used.map((c) => c.name));
  const lines = ['@startuml', '\' generated by rup-flow (index); edit the use-case cards, not this file', '!theme plain', 'skinparam linetype polyline', 'left to right direction', ''];
  const actors = actor ? [actor] : actorsOf(used);
  for (const a of actors) lines.push(`actor "${q(a)}" as A_${slug(a)}`);
  lines.push('', `rectangle "${q(project)}" {`);
  for (const [pkg, group] of groupByPackage(used)) {
    lines.push(`  package "${q(pkg)}" {`);
    for (const c of group) lines.push(`    usecase "${q(c.title)}" as UC_${slug(c.name)}`);
    lines.push('  }');
  }
  lines.push('}', '');
  for (const c of used) for (const a of c.actors) if ((!actor || a === actor) && primary(c, used)) lines.push(`A_${slug(a)} --> UC_${slug(c.name)}`);
  for (const c of used) {
    for (const target of c.includes) if (names.has(target)) lines.push(`UC_${slug(c.name)} ..> UC_${slug(target)} : <<include>>`);
    for (const target of c.extendsCases) if (names.has(target)) lines.push(`UC_${slug(c.name)} ..> UC_${slug(target)} : <<extend>>`);
  }
  lines.push('', '@enduml', '');
  return lines.join('\n');
}

/** Mermaid has no use-case diagram, so it is drawn as a flowchart with the same grouping. */
export function overviewMermaid(cases, project, actor) {
  const used = subset(cases, actor);
  const names = new Set(used.map((c) => c.name));
  const lines = ['%% generated by rup-flow (index); edit the use-case cards, not this file', 'flowchart LR'];
  const actors = actor ? [actor] : actorsOf(used);
  for (const a of actors) lines.push(`  A_${slug(a)}(["${q(a)}"])`);
  lines.push(`  subgraph SYS ["${q(project)}"]`);
  for (const [pkg, group] of groupByPackage(used)) {
    lines.push(`    subgraph P_${slug(pkg)} ["${q(pkg)}"]`);
    for (const c of group) lines.push(`      UC_${slug(c.name)}("${q(c.title)}")`);
    lines.push('    end');
  }
  lines.push('  end');
  for (const c of used) for (const a of c.actors) if ((!actor || a === actor) && primary(c, used)) lines.push(`  A_${slug(a)} --> UC_${slug(c.name)}`);
  for (const c of used) {
    for (const target of c.includes) if (names.has(target)) lines.push(`  UC_${slug(c.name)} -.->|include| UC_${slug(target)}`);
    for (const target of c.extendsCases) if (names.has(target)) lines.push(`  UC_${slug(c.name)} -.->|extend| UC_${slug(target)}`);
  }
  lines.push('');
  return lines.join('\n');
}

/** Navigation table placed at the top of every use-case card. */
export function navigation(config, name, current) {
  const link = (discipline, anchor = '') => `../../../${config.paths[discipline]}/${config.useCaseDir}/${name}/README.md${anchor}`;
  const cell = (key, label, target) => (key === current ? `**${label}**` : `[${label}](${target})`);
  return [
    '| Overview | Requirements | Analysis | Design | Implementation | Tests |',
    '| --- | --- | --- | --- | --- | --- |',
    `| [Use cases](../../../${config.paths.requirements}/use-case-overview.svg) | ${cell('requirements', 'Requirements', link('requirements'))} | ${cell('analysis', 'Analysis', link('analysis'))} | ${cell('design', 'Design', link('design'))} | ${cell('implementation', 'Implementation', link('implementation'))} | ${cell('tests', 'Tests', link('implementation', '#tests'))} |`,
  ].join('\n');
}

/** The generated block of the requirements README: index table and diagrams. */
export function indexBlock(cases, config, overviewBase) {
  const linkTo = (discipline, c) => (c.present[discipline] ? `[card](../${config.paths[discipline]}/${config.useCaseDir}/${c.name}/README.md)` : '—');
  const rows = cases.map((c) => `| ${c.id} | [${c.title}](./${config.useCaseDir}/${c.name}/README.md) | ${c.actors.join(', ')} | ${c.package} | ${c.requirement || '—'} | ${linkTo('analysis', c)} | ${linkTo('design', c)} | ${linkTo('implementation', c)} | ${c.status} |`);
  const out = [INDEX_START, '', '| ID | Use case | Actor | Package | Requirement | Analysis | Design | Implementation | Status |', '| --- | --- | --- | --- | --- | --- | --- | --- | --- |', ...(rows.length ? rows : ['| | | | | | | | | |']), ''];
  if (cases.length) {
    out.push('### Use-case diagram', '', `![Use cases](./${overviewBase}.svg)`, '');
    const actors = actorsOf(cases);
    if (actors.length > 1) {
      out.push('### By actor', '');
      for (const a of actors) out.push(`#### ${a}`, '', `![${a}](./use-cases-${slug(a).toLowerCase()}.svg)`, '');
    }
  }
  out.push(INDEX_END);
  return out.join('\n');
}

export function applyIndex(readme, block) {
  const start = readme.indexOf(INDEX_START);
  const end = readme.indexOf(INDEX_END);
  if (start >= 0 && end > start) return `${readme.slice(0, start)}${block}${readme.slice(end + INDEX_END.length)}`;
  const heading = /^## Use cases\s*$/m.exec(readme);
  if (heading) {
    const after = readme.indexOf('\n## ', heading.index + heading[0].length);
    const tail = after >= 0 ? readme.slice(after) : '\n';
    return `${readme.slice(0, heading.index + heading[0].length)}\n\n${block}\n${tail}`;
  }
  return `${readme.replace(/\s*$/, '\n')}\n## Use cases\n\n${block}\n`;
}

export function overviewFiles(cases, project, language) {
  const ext = language === 'mermaid' ? 'mmd' : 'puml';
  const draw = language === 'mermaid' ? overviewMermaid : overviewPlantuml;
  const files = [{ name: `use-case-overview.${ext}`, content: draw(cases, project) }];
  const actors = actorsOf(cases);
  if (actors.length > 1) for (const a of actors) files.push({ name: `use-cases-${slug(a).toLowerCase()}.${ext}`, content: draw(cases, project, a) });
  return files;
}
